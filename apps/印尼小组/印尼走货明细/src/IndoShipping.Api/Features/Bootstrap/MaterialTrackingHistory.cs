using System.Data;
using System.Text.Json;
using Dapper;

namespace IndoShipping.Api.Features.Bootstrap;

/// <summary>Immutable schedule/BOM revisions; never creates receipts or outbound records.</summary>
public static class MaterialTrackingHistory
{
    public const string SchemaSql = """
        CREATE TABLE IF NOT EXISTS material_tracking_history (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            schedule_id INT NOT NULL,
            week_label TEXT,
            upload_date TIMESTAMP,
            raw_rows JSONB NOT NULL,
            rows_hash TEXT NOT NULL,
            materials JSONB NOT NULL,
            products JSONB NOT NULL,
            acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
            captured_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );
        CREATE INDEX IF NOT EXISTS ix_material_tracking_history_schedule
            ON material_tracking_history(schedule_id, id DESC);
        """;

    // Caller holds one transaction across capture + schedule upsert + capture. The
    // advisory lock serializes uploads even when the week does not exist yet.
    public static async Task CaptureAsync(IDbConnection db, IDbTransaction tx)
    {
        await db.ExecuteAsync("SELECT pg_advisory_xact_lock(761024031)", transaction: tx);
        var completion = await db.ExecuteScalarAsync<string?>(
            "SELECT value FROM settings WHERE key='material_tracking_completed_schedules'", transaction: tx);
        var schedules = await db.QueryAsync<Snapshot>("""
            SELECT id AS schedule_id, week_label, upload_date, COALESCE(raw_rows,'[]'::jsonb)::text AS raw_rows,
                   md5(COALESCE(raw_rows,'[]'::jsonb)::text) AS rows_hash FROM schedules
            ORDER BY upload_date NULLS FIRST, id
            """, transaction: tx);
        var materials = await db.ExecuteScalarAsync<string>("""
            SELECT COALESCE(jsonb_agg(to_jsonb(m)), '[]')::text FROM (
                SELECT id, product_code, item_no, name_zh, category, supplier,
                       COALESCE(NULLIF(usage_qty,0),1) AS usage_qty
                FROM materials WHERE active=TRUE ORDER BY id
            ) m
            """, transaction: tx);
        var products = await db.ExecuteScalarAsync<string>("""
            SELECT COALESCE(jsonb_agg(to_jsonb(p)), '[]')::text FROM (
                SELECT code, name, moldings FROM products WHERE active=TRUE ORDER BY code
            ) p
            """, transaction: tx);
        foreach (var schedule in schedules)
        {
            var previous = await db.QueryFirstOrDefaultAsync<Snapshot>("""
                SELECT id, rows_hash FROM material_tracking_history
                WHERE schedule_id=@schedule_id ORDER BY id DESC LIMIT 1
                """, schedule, tx);
            var acknowledged = MatchesCompletion(completion, schedule.schedule_id, schedule.rows_hash);
            if (previous?.rows_hash == schedule.rows_hash)
            {
                if (acknowledged)
                    await db.ExecuteAsync("UPDATE material_tracking_history SET acknowledged=TRUE WHERE id=@id", previous, tx);
                continue;
            }
            await db.ExecuteAsync("""
                INSERT INTO material_tracking_history
                    (schedule_id,week_label,upload_date,raw_rows,rows_hash,materials,products,acknowledged)
                VALUES (@schedule_id,@week_label,@upload_date,CAST(@raw_rows AS jsonb),@rows_hash,
                        CAST(@materials AS jsonb),CAST(@products AS jsonb),@acknowledged)
                """, new { schedule.schedule_id, schedule.week_label, schedule.upload_date,
                    raw_rows = schedule.raw_rows ?? "[]", schedule.rows_hash, materials, products, acknowledged }, tx);
        }
    }

    public static bool MatchesCompletion(string? raw, int scheduleId, string? hash)
    {
        if (string.IsNullOrWhiteSpace(raw) || string.IsNullOrWhiteSpace(hash)) return false;
        try
        {
            using var doc = JsonDocument.Parse(raw);
            return doc.RootElement.ValueKind == JsonValueKind.Object
                && doc.RootElement.TryGetProperty(scheduleId.ToString(System.Globalization.CultureInfo.InvariantCulture), out var value)
                && value.ValueKind == JsonValueKind.String && value.GetString() == hash;
        }
        catch (JsonException) { return false; }
    }

    public sealed class Snapshot
    {
        public long id { get; set; }
        public int schedule_id { get; set; }
        public string? week_label { get; set; }
        public DateTime? upload_date { get; set; }
        public string? raw_rows { get; set; }
        public string? rows_hash { get; set; }
        public string materials { get; set; } = "[]";
        public string products { get; set; } = "[]";
        public bool acknowledged { get; set; }
    }
}
