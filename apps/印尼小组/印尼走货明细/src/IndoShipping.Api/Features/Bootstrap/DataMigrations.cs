using System.Data;
using System.Text.Json;
using Dapper;
using IndoShipping.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;

namespace IndoShipping.Api.Features.Bootstrap;

/// <summary>
/// Applies one-time, idempotent corrections to existing production data.
/// Each migration records a marker in settings so user edits made afterwards
/// are not overwritten on every application restart.
/// </summary>
public static class DataMigrations
{
    private const string ReplaceHsDictionaryKey =
        "data_migration:2026-08-13-replace-hs-dictionary-v1";

    private const string BackfillTranslationsKey =
        "data_migration:2026-08-15-backfill-translations-v1";

    private const string BackfillSuppliersKey =
        "data_migration:2026-09-05-backfill-supplier-dictionary-v1";

    public static async Task ApplyAsync(AppDbContext db, ILogger logger)
    {
        var connection = db.Database.GetDbConnection();
        if (connection.State != ConnectionState.Open)
            await connection.OpenAsync();

        // Bootstrap existing schedules once, then retain each subsequent upload's BOM.
        await connection.ExecuteAsync(MaterialTrackingHistory.SchemaSql);
        await using (var historyTx = await connection.BeginTransactionAsync())
        {
            await MaterialTrackingHistory.CaptureAsync(connection, historyTx);
            await historyTx.CommitAsync();
        }

        // 独立非生产物料复用全局物料 ID，但不挂入 products/BOM。
        await using (var tools = connection.CreateCommand())
        {
            tools.CommandText = """
                CREATE TABLE IF NOT EXISTS tool_materials (
                    material_id INT PRIMARY KEY REFERENCES materials(id) ON DELETE CASCADE,
                    related_product_code VARCHAR(64) NOT NULL DEFAULT '',
                    tool_kind VARCHAR(16) NOT NULL CONSTRAINT tool_materials_kind_v2_check CHECK (tool_kind IN ('工具','机器设备')),
                    revision INT NOT NULL DEFAULT 1
                );
                DO $$
                BEGIN
                    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                        WHERE conrelid='tool_materials'::regclass AND conname='tool_materials_kind_v2_check') THEN
                        ALTER TABLE tool_materials DROP CONSTRAINT IF EXISTS tool_materials_tool_kind_check;
                        UPDATE tool_materials SET tool_kind=CASE WHEN tool_kind='设备' THEN '机器设备' ELSE '工具' END,
                            revision=revision+1 WHERE tool_kind IN ('模具','耗材','设备');
                        UPDATE materials m SET category=t.tool_kind FROM tool_materials t
                            WHERE m.id=t.material_id AND m.category IN ('模具','耗材','设备');
                        UPDATE po_items p SET category=t.tool_kind FROM tool_materials t
                            WHERE p.material_id=t.material_id AND p.category IN ('模具','耗材','设备');
                        ALTER TABLE tool_materials ADD CONSTRAINT tool_materials_kind_v2_check
                            CHECK (tool_kind IN ('工具','机器设备'));
                    END IF;
                END $$;
                ALTER TABLE tool_materials ADD COLUMN IF NOT EXISTS purchase_price DECIMAL(18,6) NULL;
                ALTER TABLE tool_materials ADD COLUMN IF NOT EXISTS purchase_currency VARCHAR(3) NULL;
                """;
            await tools.ExecuteNonQueryAsync();
        }

        // This is deliberately outside the one-time HS migration below: older databases
        // must receive the translation-memory table even when the HS marker already exists.
        await using (var ensureTranslations = connection.CreateCommand())
        {
            ensureTranslations.CommandText = """
                CREATE TABLE IF NOT EXISTS dict_translation (
                    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    keyword VARCHAR(256) NOT NULL,
                    english_name VARCHAR(512) NOT NULL,
                    active BOOLEAN NOT NULL DEFAULT TRUE,
                    source VARCHAR(32) NOT NULL DEFAULT 'manual',
                    priority INT NOT NULL DEFAULT 100,
                    updated_at TIMESTAMP(0) NOT NULL DEFAULT now(),
                    CONSTRAINT "UQ_dict_translation_keyword" UNIQUE (keyword)
                );
                CREATE INDEX IF NOT EXISTS "IX_dict_translation_active"
                    ON dict_translation(active, priority);
                """;
            await ensureTranslations.ExecuteNonQueryAsync();
        }

        // 供应商汇总直接扩展现有字典记录，历史简称/全称自动保留为档案的中文名称。
        await using (var ensureSupplierProfiles = connection.CreateCommand())
        {
            ensureSupplierProfiles.CommandText = """
                ALTER TABLE dict_supplier ADD COLUMN IF NOT EXISTS name_en TEXT NOT NULL DEFAULT '';
                ALTER TABLE dict_supplier ADD COLUMN IF NOT EXISTS address_zh TEXT NOT NULL DEFAULT '';
                ALTER TABLE dict_supplier ADD COLUMN IF NOT EXISTS address_en TEXT NOT NULL DEFAULT '';
                ALTER TABLE dict_supplier ADD COLUMN IF NOT EXISTS phone TEXT NOT NULL DEFAULT '';
                ALTER TABLE dict_supplier ADD COLUMN IF NOT EXISTS email TEXT NOT NULL DEFAULT '';
                ALTER TABLE dict_supplier ADD COLUMN IF NOT EXISTS contact TEXT NOT NULL DEFAULT '';
                UPDATE dict_supplier
                SET customs_company = COALESCE(NULLIF(trim(full_name), ''), trim(keyword))
                WHERE trim(COALESCE(customs_company, '')) = '';
                """;
            await ensureSupplierProfiles.ExecuteNonQueryAsync();
        }

        // 走货行称重数量：旧数据库启动时幂等补列，避免保存后丢失。
        await using (var ensureWeighingQty = connection.CreateCommand())
        {
            ensureWeighingQty.CommandText = "ALTER TABLE shipment_items ADD COLUMN IF NOT EXISTS weighing_qty DECIMAL(18,4) NULL; ALTER TABLE shipment_items ADD COLUMN IF NOT EXISTS carton_group VARCHAR(64) NULL; ALTER TABLE shipment_items ADD COLUMN IF NOT EXISTS material_snapshot JSONB NULL; ALTER TABLE shipment_items ADD COLUMN IF NOT EXISTS carton_no VARCHAR(256) NULL;";
            await ensureWeighingQty.ExecuteNonQueryAsync();
        }

        // 入库备品数量单独记录：不冲减采购欠数，但计入可用库存。
        await using (var ensureReceiptSpareQty = connection.CreateCommand())
        {
            ensureReceiptSpareQty.CommandText = "ALTER TABLE po_receipts ADD COLUMN IF NOT EXISTS spare_qty DECIMAL(18,4) NOT NULL DEFAULT 0;";
            await ensureReceiptSpareQty.ExecuteNonQueryAsync();
        }

        // 历史物料回填只执行一次（settings 一次性标记）：否则用户在字典页删除的条目
        // 会在每次重启后复活，与字典「删除」能力矛盾
        await using (var backfillClaim = connection.CreateCommand())
        {
            backfillClaim.CommandText = $"""
                INSERT INTO settings ("key", value, updated_at)
                VALUES ('{BackfillTranslationsKey}', 'applied', now())
                ON CONFLICT ("key") DO NOTHING
                RETURNING 1;
                """;
            if (await backfillClaim.ExecuteScalarAsync() is not null)
            {
                await using var backfill = connection.CreateCommand();
                backfill.CommandText = """
                    INSERT INTO dict_translation(keyword, english_name, source, priority)
                    SELECT trim(name_zh), min(trim(name_en)), 'existing-material', 100
                    FROM materials
                    WHERE trim(COALESCE(name_zh, '')) <> '' AND trim(COALESCE(name_en, '')) <> ''
                    GROUP BY trim(name_zh)
                    HAVING COUNT(DISTINCT lower(trim(name_en))) = 1
                    ON CONFLICT (keyword) DO NOTHING;
                    """;
                await backfill.ExecuteNonQueryAsync();
            }
        }

        // 旧版货号保存流程只把供应商写入 materials，没有同步到供应商字典。
        // 一次性补录历史供应商；只新增缺失项，绝不覆盖字典中已经维护的内容。
        await using (var supplierBackfillClaim = connection.CreateCommand())
        {
            supplierBackfillClaim.CommandText = $"""
                INSERT INTO settings ("key", value, updated_at)
                VALUES ('{BackfillSuppliersKey}', 'applied', now())
                ON CONFLICT ("key") DO NOTHING
                RETURNING 1;
                """;
            if (await supplierBackfillClaim.ExecuteScalarAsync() is not null)
            {
                await using var supplierBackfill = connection.CreateCommand();
                supplierBackfill.CommandText = """
                    WITH source AS (
                        SELECT
                            min(trim(supplier)) AS keyword,
                            max(NULLIF(trim(COALESCE(customs_company, '')), '')) AS customs_company
                        FROM materials
                        WHERE trim(COALESCE(supplier, '')) <> ''
                        GROUP BY lower(trim(supplier))
                    ), missing AS (
                        SELECT
                            source.keyword,
                            source.customs_company,
                            row_number() OVER (ORDER BY source.keyword) AS row_number
                        FROM source
                        WHERE NOT EXISTS (
                            SELECT 1
                            FROM dict_supplier existing
                            WHERE lower(trim(existing.keyword)) = lower(source.keyword)
                               OR lower(trim(COALESCE(existing.full_name, ''))) = lower(source.keyword)
                        )
                    ), current_priority AS (
                        SELECT COALESCE(max(priority), 0) AS value
                        FROM dict_supplier
                    )
                    INSERT INTO dict_supplier(keyword, full_name, customs_company, priority)
                    SELECT
                        missing.keyword,
                        missing.keyword,
                        missing.customs_company,
                        current_priority.value + (missing.row_number * 10)::int
                    FROM missing
                    CROSS JOIN current_priority;
                    """;
                var inserted = await supplierBackfill.ExecuteNonQueryAsync();
                logger.LogInformation("Backfilled {Count} suppliers from saved materials.", inserted);
            }
        }

        await using var transaction = await connection.BeginTransactionAsync(IsolationLevel.Serializable);

        await using var claim = connection.CreateCommand();
        claim.Transaction = transaction;
        claim.CommandText = $"""
            INSERT INTO settings ("key", value, updated_at)
            VALUES ('{ReplaceHsDictionaryKey}', 'running', now())
            ON CONFLICT ("key") DO NOTHING
            RETURNING 1;
            """;

        if (await claim.ExecuteScalarAsync() is null)
        {
            await transaction.RollbackAsync();
            return;
        }

        var entries = await LoadHsDictionaryAsync();
        if (entries.Count == 0)
            throw new InvalidOperationException("Bundled HS dictionary is empty; refusing to replace existing data.");
        if (entries.Any(entry => entry.HsId.Length != 8 || !entry.HsId.All(char.IsDigit)))
            throw new InvalidOperationException("Every Indonesian HS code must contain exactly eight digits.");
        if (entries.GroupBy(entry => entry.Keyword, StringComparer.OrdinalIgnoreCase).Any(group => group.Count() > 1))
            throw new InvalidOperationException("Bundled HS dictionary contains duplicate keywords.");

        await using var replace = connection.CreateCommand();
        replace.Transaction = transaction;
        replace.CommandText = "DELETE FROM dict_hs;";
        await replace.ExecuteNonQueryAsync();

        await using var insert = connection.CreateCommand();
        insert.Transaction = transaction;
        insert.CommandText = """
            INSERT INTO dict_hs (keyword, hs_cn, hs_id, priority)
            VALUES (@keyword, @hs_cn, @hs_id, @priority);
            """;
        var keyword = insert.CreateParameter(); keyword.ParameterName = "keyword"; insert.Parameters.Add(keyword);
        var hsCn = insert.CreateParameter(); hsCn.ParameterName = "hs_cn"; insert.Parameters.Add(hsCn);
        var hsId = insert.CreateParameter(); hsId.ParameterName = "hs_id"; insert.Parameters.Add(hsId);
        var priority = insert.CreateParameter(); priority.ParameterName = "priority"; insert.Parameters.Add(priority);

        foreach (var entry in entries)
        {
            keyword.Value = entry.Keyword;
            hsCn.Value = entry.HsCn;
            hsId.Value = entry.HsId;
            priority.Value = entry.Priority;
            await insert.ExecuteNonQueryAsync();
        }

        await using var complete = connection.CreateCommand();
        complete.Transaction = transaction;
        complete.CommandText = $"""
            UPDATE settings
            SET value = 'applied', updated_at = now()
            WHERE "key" = '{ReplaceHsDictionaryKey}';
            """;
        await complete.ExecuteNonQueryAsync();
        await transaction.CommitAsync();

        logger.LogInformation("Replaced HS dictionary with {Count} validated entries.", entries.Count);
    }

    private static async Task<IReadOnlyList<HsDictionaryEntry>> LoadHsDictionaryAsync()
    {
        var path = Path.Combine(AppContext.BaseDirectory, "seed", "hs-dictionary.json");
        if (!File.Exists(path))
            throw new FileNotFoundException($"Bundled HS dictionary not found: {path}");

        await using var stream = File.OpenRead(path);
        return await JsonSerializer.DeserializeAsync<List<HsDictionaryEntry>>(
                   stream,
                   new JsonSerializerOptions { PropertyNameCaseInsensitive = true })
               ?? [];
    }

    private sealed record HsDictionaryEntry(string Keyword, string HsCn, string HsId, int Priority);
}
