-- ========== 2. 塑胶共用物料表:92125 加工内容按排模表纠正 ==========
-- 现状:全表 3075 行均属 92125 家族(塑胶货号全部 92125 开头,已 SELECT 确认),
-- 加工内容 喷油×3074/NULL×1 为之前导入的默认值,与排模表不符。
-- 纠正:公仔+手链蛋黄形件→移印,大角→印喷,其余→NULL(排模表无二次加工依据)。
-- 影响:塑胶采购订单「喷油」过滤命中范围随之收窄——这正是本次目的。
UPDATE [塑胶共用物料表] SET [加工内容]=N'移印'
WHERE [塑胶货号] LIKE N'92125%'
  AND ([物料编号] LIKE N'RBCEZ2-08M-01-%' OR [物料编号] LIKE N'RBCEZ-07M-005-%')
  AND ([加工内容] IS NULL OR [加工内容]<>N'移印');
PRINT N'塑胶共用物料表 公仔/手链蛋黄形件→移印: ' + CAST(@@ROWCOUNT AS nvarchar(10)) + N' 行';

UPDATE [塑胶共用物料表] SET [加工内容]=N'印喷'
WHERE [塑胶货号] LIKE N'92125%' AND [物料编号] LIKE N'RAINB-7M-01-%'
  AND ([加工内容] IS NULL OR [加工内容]<>N'印喷');
PRINT N'塑胶共用物料表 大角→印喷: ' + CAST(@@ROWCOUNT AS nvarchar(10)) + N' 行';

UPDATE [塑胶共用物料表] SET [加工内容]=NULL
WHERE [塑胶货号] LIKE N'92125%'
  AND [物料编号] NOT LIKE N'RBCEZ2-08M-01-%' AND [物料编号] NOT LIKE N'RBCEZ-07M-005-%'
  AND [物料编号] NOT LIKE N'RAINB-7M-01-%'
  AND [加工内容] IS NOT NULL;
PRINT N'塑胶共用物料表 其余 92125 行→NULL: ' + CAST(@@ROWCOUNT AS nvarchar(10)) + N' 行';

-- ========== 3. 工模表:补排模表 col23 备注(堵模啤/水口),追加不覆盖 ==========
-- 排模表零件行备注(6 sheet 一致):
--   RBCEZ-07M-001 莲花底座 / RBCEZ-07M-003 戒指 → 模具 RBCEZ-07M-01-1,备注「堵模啤」
