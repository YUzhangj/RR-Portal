-- 采购入仓明细单.备品数量:供应商多送的备品单列。
-- 此前口径:整行 备品='1',数量=备品量(订单数量与备品数量混在一列,无法表达"订单 99020 + 备品 980"的同单拆分)。
-- 统一口径:数量=计入订单欠数的部分;备品数量=备品部分(不占订单欠数,审核后计入可用库存);
--          实物入库=数量+备品数量;金额只按 数量 计(备品免费)。
-- 存量整行备品拆出:数量→备品数量、数量置 0——单头合计/库存聚合/订单进度口径不变。
IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID(N'[dbo].[采购入仓明细单]') AND name=N'备品数量')
    ALTER TABLE [dbo].[采购入仓明细单] ADD [备品数量] decimal(18,4) NULL;
GO
UPDATE [dbo].[采购入仓明细单] SET [备品数量]=[数量],[数量]=0
WHERE [备品]='1' AND ISNULL([备品数量],0)=0 AND ISNULL([数量],0)<>0;
GO
