const START_B = 104;
const STOP = 106;

export interface BarModule { bar: boolean; width: number }

// 编码文本 → 模块序列（条/空交替）。非法字符（非 ASCII 32-126）抛错由调用方处理。
export function encodeCode128B(text: string): BarModule[] {
  const values: number[] = [START_B];
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    if (code < 32 || code > 126) throw new Error(`条码仅支持英文/数字/符号，含非法字符: ${ch}`);
    values.push(code - 32);
  }
  // 校验码 = (start + Σ value[i]*i) % 103，i 从 1 开始
  let sum = values[0];
  for (let i = 1; i < values.length; i++) sum += values[i] * i;
  values.push(sum % 103);
  values.push(STOP);

  const modules: BarModule[] = [];
  for (const v of values) {
    const widths = PATTERNS[v];
    widths.forEach((w, i) => modules.push({ bar: i % 2 === 0, width: w }));
  }
  return modules;
}

// 计算总宽度（模块数），便于设定 SVG viewBox
export function totalModules(modules: BarModule[]): number {
  return modules.reduce((s, m) => s + m.width, 0);
}
